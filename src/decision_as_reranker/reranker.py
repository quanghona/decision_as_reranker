"""Typed decision model as a reranker for RAG.

`BaseDecisionReranker` owns everything mechanical: building the request, calling the decision model
through a backend adapter, parsing the typed answers into one float per candidate, and ordering the
candidates. A subclass supplies only the questions to ask -- the transport, the parsing and the
ranking policy live in the base and are not reimplemented per primitive.

The serving instance is whichever `BaseDecisionBackend` you inject: one speaking the TypeSafe
System One contract (hosted Jev, a self-hosted Kev (github.com/jaredpalmer/kev), Microsoft
Decision, Cloudflare Clef, or a gateway in front of any of them), or one speaking an
OpenAI-compatible API. The reranker itself knows neither SDK nor HTTP -- see
`decision_as_reranker.backend`.

Two invariants hold throughout:

* A failed call is never turned into a score. Errors propagate (`on_error="raise"`, the default)
  or mark the candidates unscored and exclude them (`on_error="drop"`). `0.0` always means "the
  model said irrelevant", never "the network hiccuped".
* Ordering is by score, then by input position. Float ties are common near 0 and 1, and without a
  tie-break the output depends on iteration order instead of the data.
"""

from __future__ import annotations

import abc
import logging
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Literal

from decision_as_reranker.backend.base import (
    BaseDecisionBackend,
    ChoiceAnswer,
    DecisionResponse,
    NoulAnswer,
    Question,
    ScoreAnswer,
)

logger = logging.getLogger(__name__)

#: What happens to candidates the model could not be reached for.
OnError = Literal["raise", "drop"]


@dataclass(frozen=True)
class ScoredCandidate:
    """One candidate, the relevance the decision model assigned it, and where it came in."""

    candidate: str
    score: float
    index: int


@dataclass(frozen=True)
class DecisionQuery:
    """A question plus the candidates its answer scores.

    * One question per candidate: `DecisionQuery(Noul(...), {3: None})`.
    * One `choice` over all candidates: `DecisionQuery(Choice(criteria={"d0": ..., "d1": ...}),
      {0: "d0", 1: "d1"})` -- the options *are* the candidates, so one comparison ranks them all.
    * Several signals for one candidate: pass several queries to `score`; the values are averaged.

    Question ids are generated by the base class and never reach the model, so they carry no meaning
    beyond identity. Option names *do* reach the model: keep them short and non-semantic (`d0`, `d1`)
    and put the content in the description, or the labels bias the answer.

    Args:
        question: The `Question` to ask.
        targets: Candidate index to the option whose probability to read from the answer, or `None`
            when the answer itself is the value (`noul`, and `score` normalised to `[0, 1]`). Must
            be non-empty.
    """

    question: Question
    targets: Mapping[int, str | None]

    def __post_init__(self) -> None:
        if not self.targets:
            raise ValueError("DecisionQuery needs at least one target candidate")
        for index, option in self.targets.items():
            if not isinstance(index, int) or isinstance(index, bool) or index < 0:
                raise ValueError(f"target index {index!r} is not a non-negative int")
            if option is not None and not isinstance(option, str):
                raise ValueError(f"option for candidate {index} is {option!r}, not str or None")


class BaseDecisionReranker(abc.ABC):
    """Backend call, parsing and ordering layer over a decision model.

    Concrete about the backend (`ask`, `score`, `rank`), abstract about the questions. A subclass
    implements `rerank`, builds its `DecisionQuery` list, and calls `score`/`rank` -- it should not
    reach past the backend, read `response.answers` by hand, or write its own sort. Override `ask`
    alone when a different request shape is needed (splitting a long shortlist across several
    calls, retrying per chunk); the parsing and ordering below then still apply.

    Args:
        backend: The adapter to call -- and the single place the answering model is configured
            (see `BaseDecisionBackend`); the reranker forwards no per-call model. Always the
            caller's: the reranker never constructs one and never closes one -- a backend's
            lifecycle belongs to whoever configured its endpoint. Share one instance across
            rerankers and queries instead of paying a handshake per call. Log the model id every
            response carries: a threshold tuned against an alias drifts when the alias moves.
        on_error: `"raise"` lets a transport failure abort the call; `"drop"` records the affected
            candidates as unscored and ranks the rest. Which exceptions count as transport
            failures is the backend's `transport_errors` -- the reranker hardcodes none.
    """

    def __init__(
        self,
        backend: BaseDecisionBackend,
        *,
        on_error: OnError = "raise",
    ) -> None:
        if on_error not in ("raise", "drop"):
            raise ValueError(f"on_error must be 'raise' or 'drop', got {on_error!r}")
        self._backend = backend
        self.on_error: OnError = on_error

    # --------------------------------------------------------------- the injected adapter

    @property
    def backend(self) -> BaseDecisionBackend:
        """The adapter this reranker calls. Owned by the caller; closing it is the caller's job."""
        return self._backend

    # --------------------------------------------------------------- subclass surface

    @abc.abstractmethod
    def rerank(self, query: str, candidates: Sequence[str], k: int | None = None) -> list[ScoredCandidate]:
        """Order `candidates` for `query`, best first.

        Implemented by the subclasses; `score` and `rank` are the parts. The query is a parameter and
        never instance state: one reranker serves many queries, so storing the current one on `self`
        would make concurrent calls answer each other.

        Args:
            query: The information need the candidates were shortlisted against.
            candidates: The passages to rank, in input order.
            k: How many to keep; `None` keeps every scored candidate.

        Returns:
            The scored candidates, ordered by score then input position, as `rank` produces them.
        """

    def build_state(self, query: str) -> Mapping[str, object]:
        """The `state` sent with the request: the query, which is read once for all questions.

        Candidate text belongs in the questions, not here. `state` is shared by every question in a
        request, so putting one candidate in it scores every candidate against that one.

        Args:
            query: The retrieval query.

        Returns:
            The state mapping for the request envelope.
        """
        return {"query": query}

    # --------------------------------------------------------------- the one backend call site

    def ask(self, state: Mapping[str, object], questions: Mapping[str, Question]) -> DecisionResponse:
        """Send one decision request. The only place this package touches a backend.

        Args:
            state: Context shared by every question, from `build_state`.
            questions: Question id to question.

        Returns:
            The backend's `DecisionResponse`.
        """
        return self._backend.ask(state, questions)

    # --------------------------------------------------------------- scoring

    def score(self, query: str, candidates: Sequence[str], decisions: Sequence[DecisionQuery]) -> list[float | None]:
        """Ask the model once and return one relevance in `[0, 1]` per candidate, in input order.

        `None` marks a candidate that could not be scored; that happens only under
        `on_error="drop"`, and never as a numeric stand-in for a failure.

        Args:
            query: The retrieval query.
            candidates: The passages to score, in input order.
            decisions: The `DecisionQuery` list to ask. A candidate targeted by several queries
                receives the mean of their values.

        Returns:
            One score (or `None`) per candidate, positionally aligned with `candidates`; empty when
            `candidates` is empty.

        Raises:
            ValueError: `decisions` is empty, or a candidate index appears in no query's targets.
            KeyError: A question came back with no answer and `on_error="raise"`.
            BaseException: Whatever the backend's `transport_errors` name, when `on_error="raise"`.
        """
        if not candidates:
            return []

        decisions = list(decisions)
        if not decisions:
            raise ValueError("score needs at least one DecisionQuery to ask")

        questions: dict[str, Question] = {}
        asked: list[tuple[str, Mapping[int, str | None]]] = []
        declared: set[int] = set()
        for position, decision in enumerate(decisions):
            question_id = f"q{position}"
            questions[question_id] = decision.question
            asked.append((question_id, decision.targets))
            declared.update(decision.targets)

        # Which exceptions mean "unreachable" is the backend's claim, not a list here; a bare
        # ValueError/TypeError out of `ask` is a wiring bug and no policy swallows it.
        try:
            response = self.ask(self.build_state(query), questions)
        except self._backend.transport_errors as exc:
            if self.on_error == "raise":
                raise
            logger.warning("decision model unavailable (%s); leaving %d candidate(s) unscored", exc, len(candidates))
            return [None] * len(candidates)

        # Provenance (which model answered) is logged by `BaseDecisionBackend.ask`; nothing in the
        # ranking path may read `usage` or `request_id`.
        collected: dict[int, list[float]] = {}
        for question_id, targets in asked:
            answer = response.answers.get(question_id)
            if answer is None:
                if self.on_error == "raise":
                    raise KeyError(f"backend returned no answer for question {question_id!r}")
                logger.warning(
                    "backend returned no answer for %s; leaving candidates %s unscored",
                    question_id,
                    sorted(targets),
                )
                continue
            for index, option in targets.items():
                collected.setdefault(index, []).append(_answer_value(answer, option, question_id))

        # A candidate no question *declares* is a wiring mistake, not a backend failure, so it
        # raises whatever `on_error` says -- that policy covers unreachable backends, not a bad
        # `targets` map. A declared candidate with no answer came from the backend and follows it.
        untargeted = sorted(set(range(len(candidates))) - declared)
        if untargeted:
            raise ValueError(
                f"candidates {untargeted} are not targeted by any DecisionQuery; every candidate "
                "index must appear in at least one query's targets"
            )

        values: list[float | None] = []
        for index in range(len(candidates)):
            found = collected.get(index)
            values.append(sum(found) / len(found) if found else None)
        return values

    # --------------------------------------------------------------- ordering

    def rank(
        self,
        candidates: Sequence[str],
        scores: Sequence[float | None],
        k: int | None = None,
    ) -> list[ScoredCandidate]:
        """Order candidates by relevance, best first, keeping the top `k`.

        Duplicate texts stay separate -- they arrive from different documents and must not collapse
        into one score. Unscored candidates are excluded, not ranked last.

        Args:
            candidates: The passages, in input order.
            scores: One score (or `None`) per candidate, positionally aligned with `candidates`.
            k: How many to keep; `None` keeps all of them.

        Returns:
            The scored candidates, ordered by score then input position.

        Raises:
            ValueError: `k` is negative, or `scores` and `candidates` differ in length.
        """
        if k is not None and k < 0:
            raise ValueError(f"k must be non-negative, got {k}")
        if len(scores) != len(candidates):
            raise ValueError(f"got {len(scores)} scores for {len(candidates)} candidates")
        ranked = [
            ScoredCandidate(candidate=candidate, score=value, index=index)
            for index, (candidate, value) in enumerate(zip(candidates, scores))
            if value is not None
        ]
        ranked.sort(key=lambda scored: (-scored.score, scored.index))
        return ranked[:k] if k is not None else ranked


def _answer_value(answer: object, option: str | None, question_id: str) -> float:
    """Reduce one typed answer to a relevance in `[0, 1]`.

    Dispatches on the neutral answer classes from `decision_as_reranker.backend`; a provider's own
    answer objects cannot reach here -- `DecisionResponse` rejects them at construction. There is no
    `confidence` to read: the contract omits it on purpose (see `backend`'s module docstring).

    Args:
        answer: The neutral `Answer` for one question.
        option: For a `choice`, the option whose probability to read; `None` otherwise.
        question_id: The question's id, used in error messages.

    Returns:
        The relevance in `[0, 1]`.

    Raises:
        ValueError: A `choice` answer with no option named, an option missing from the answer, or
            an off-contract value.
        TypeError: `answer` is not one of the neutral answer classes.
    """
    if isinstance(answer, NoulAnswer):
        return _in_unit_interval(answer.noul, question_id)
    if isinstance(answer, ChoiceAnswer):
        if option is None:
            raise ValueError(f"question {question_id!r} is a choice: name the option to score in DecisionQuery.targets")
        try:
            return _in_unit_interval(answer.probabilities[option], question_id)
        except KeyError:
            known = ", ".join(sorted(answer.probabilities))
            raise ValueError(f"question {question_id!r} returned options [{known}]; asked for {option!r}") from None
    if isinstance(answer, ScoreAnswer):
        # `score` is the probability-weighted mean level index, so it lives on the level line rather
        # than in [0, 1]. Dividing by the top index makes it comparable with the other primitives --
        # a scale change only, not a recalibration.
        levels = len(answer.probabilities) or len(answer.legend)
        value = answer.score if levels < 2 else answer.score / (levels - 1)
        return _in_unit_interval(value, question_id)
    raise TypeError(f"unsupported answer type {type(answer).__name__} for question {question_id!r}")


def _in_unit_interval(value: float, question_id: str) -> float:
    """Return `value` unchanged, checking it lies in `[0, 1]`.

    Args:
        value: The candidate relevance.
        question_id: The question's id, used in the error message.

    Returns:
        `value`, unchanged.

    Raises:
        ValueError: `value` is outside `[0, 1]` -- the backend is off-contract.
    """
    if not 0.0 <= value <= 1.0:
        raise ValueError(f"question {question_id!r} returned {value!r}, outside [0, 1] -- backend is off-contract")
    return value


